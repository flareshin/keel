from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import shlex
import sys

from files import digest, fingerprint, read_json, write_atomic
from skill_registry import apply_skill_plan, installation_lock, plan_skills

ADAPTER = Path(__file__).resolve().parents[1]
KEEL = ADAPTER.parent
STATE_NAME = 'keel-codex-state.json'


def main() -> int:
    parser = argparse.ArgumentParser(description='Install the separate keel Codex adapter; default: dry run.')
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--write', action='store_true')
    mode.add_argument('--check', action='store_true')
    mode.add_argument('--unlink', action='store_true')
    parser.add_argument('--home', type=Path, default=Path.home())
    args = parser.parse_args()
    home = args.home.expanduser().resolve()
    codex_home = Path(os.environ.get('CODEX_HOME', str(home / '.codex'))).expanduser().resolve()
    overlay = Path(os.environ.get('KEEL_OVERLAY_DIR', str(home / 'git/keel-overlay'))).expanduser().resolve()
    data = Path(os.environ.get('KEEL_DATA_DIR', str(home / '.claude'))).expanduser().absolute()
    try:
        with installation_lock(home / '.agents', args.write or args.unlink):
            desired = {} if args.unlink else build_files(codex_home, overlay, data, home / '.agents')
            skills = {} if args.unlink else build_skill_links(home, overlay)
            return reconcile(desired, skills, home / '.agents', codex_home / STATE_NAME, args)
    except (OSError, ValueError) as error:
        print(f'codex/link: refused: {error}', file=sys.stderr)
        return 3


def build_files(codex_home: Path, overlay: Path, data: Path, agents_home: Path) -> dict:
    principles = (KEEL / 'PRINCIPLES.md').read_text()
    personal = overlay / 'PERSONAL.md'
    owner = personal.read_text() if personal.is_file() else ''
    runtime = (ADAPTER / 'AGENTS.md').read_text()
    paths = {'KEEL_HOME': str(KEEL), 'KEEL_OVERLAY_DIR': str(overlay), 'KEEL_DATA_DIR': str(data)}
    locations = '\n'.join(f'- {key}: `{value}`' for key, value in paths.items())
    agents = '<!-- Generated by keel/codex/bin/link; edit the sources. -->\n'
    agents += '\n'.join((principles, owner, runtime, '## Runtime paths', locations,
                         f'- keel CLI: `{KEEL / "bin/keel"}`\n'))
    paths['KEEL_CODEX_HOME'] = str(codex_home)
    paths['KEEL_AGENTS_HOME'] = str(agents_home)
    assignments = ' '.join(f'{key}={shlex.quote(value)}' for key, value in paths.items())
    command = f'{assignments} {shlex.quote(sys.executable)} {shlex.quote(str(ADAPTER / "hooks/pre-tool-use.py"))}'
    hooks = {'hooks': {'PreToolUse': [{'matcher': 'Bash|apply_patch|Edit|Write', 'hooks': [
        {'type': 'command', 'command': command, 'timeout': 90}]}]}}
    return {codex_home / 'AGENTS.md': ('file', agents),
            codex_home / 'hooks.json': ('file', json.dumps(hooks, indent=2) + '\n')}


def build_skill_links(home: Path, overlay: Path) -> dict:
    links = {}
    for root in (KEEL / 'skills', overlay / 'skills', ADAPTER / 'skills'):
        if not root.is_dir():
            continue
        for skill in sorted(root.iterdir()):
            if not (skill / 'SKILL.md').is_file():
                continue
            target = home / '.agents/skills' / skill.name
            if target in links:
                raise ValueError(f'duplicate skill: {skill.name}')
            links[target] = ('link', str(skill.resolve()))
    return links


def reconcile(desired: dict, skills: dict, agents_home: Path, state_path: Path, args: argparse.Namespace) -> int:
    owned, migrated = read_profile(state_path, agents_home)
    skill_plan = plan_skills(agents_home, state_path.parent, skills)
    changes, problems = plan_files(desired, owned)
    problems.extend(skill_plan.problems)
    actions = [str(path) for path in changes] + [str(path) for path in skill_plan.create]
    actions += [f'retarget {path}' for path in skill_plan.replace]
    actions += [f'remove {path}' for path in skill_plan.remove]
    if skill_plan.changed:
        actions.append('update shared skill references')
    if migrated:
        actions.append('migrate profile ownership; preserve legacy skill links')
    if problems:
        print(json.dumps({'actions': actions, 'problems': problems, 'written': 0}))
        return 3 if args.write or args.unlink else (1 if args.check else 0)
    if args.unlink:
        apply_skill_plan(agents_home, skill_plan)
        for name in owned:
            Path(name).unlink(missing_ok=True)
        state_path.unlink(missing_ok=True)
        print(json.dumps({'removed': len(owned) + len(skill_plan.remove)}))
        return 0
    if args.write:
        for path in changes:
            write_atomic(path, desired[path][1])
            owned[str(path)] = digest(*desired[path])
        apply_skill_plan(agents_home, skill_plan)
        for path, payload in desired.items():
            if str(path) in owned:
                owned[str(path)] = digest(*payload)
        write_atomic(state_path, json.dumps({'owned': owned, 'skills_home': str(agents_home)}, indent=2) + '\n')
    print(json.dumps({'actions': actions, 'problems': []}))
    return 1 if args.check and actions else 0


def read_profile(state_path: Path, agents_home: Path) -> tuple[dict, bool]:
    state = read_json(state_path)
    owned = state.get('owned', {})
    if not isinstance(owned, dict) or any(not isinstance(k, str) or not isinstance(v, str) for k, v in owned.items()):
        raise ValueError(f'invalid ownership state: {state_path}')
    if state.get('skills_home', str(agents_home)) != str(agents_home):
        raise ValueError('profile belongs to a different skills home; use its original --home')
    allowed = {str(state_path.parent / name) for name in ('AGENTS.md', 'hooks.json')}
    legacy = {name for name in owned if Path(name).parent == agents_home / 'skills'}
    if set(owned) - allowed - legacy:
        raise ValueError('profile ownership contains an unexpected path')
    return {name: value for name, value in owned.items() if name not in legacy}, bool(state and 'skills_home' not in state)


def plan_files(desired: dict, owned: dict) -> tuple[list, list]:
    changes, problems = [], []
    expected = {str(path): digest(*payload) for path, payload in desired.items()}
    for name, recorded in owned.items():
        if fingerprint(Path(name)) not in (None, recorded, expected.get(name)):
            problems.append(f'managed path edited: {name}')
    for path, (kind, content) in desired.items():
        current = fingerprint(path)
        if current == digest(kind, content):
            continue
        if current is not None and current != owned.get(str(path)):
            problems.append(f'conflict: {path}; preserve it and reconcile manually')
        else:
            changes.append(path)
    return changes, problems

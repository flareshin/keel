export const KEEL_ROOT = dirname(dirname(dirname(resolvePath(import.meta.filename))));
export const STATE_NAME = "keel-codex-state.json";
export const HOOK_SCRIPT = "codex/hooks/pre-tool-use.ts";

const REFUSED_EXIT_CODE = 3;
const CHECK_PENDING_EXIT_CODE = 1;
const HOOK_TIMEOUT_SECONDS = 90;
const JSON_INDENT = 2;
const GENERATED_HEADER = "<!-- Generated by keel/codex/bin/link; edit the sources. -->\n";
const MODE_FLAGS = ["write", "check", "unlink"] as const;

const LINK_COMMAND: CommandSpec = {
  prog: "link",
  usage: "link [-h] [--write | --check | --unlink] [--home HOME]",
  description: "Install the separate keel Codex adapter; default: dry run.",
  argumentHelp: [["--write", "install the adapter"], ["--check", "report pending changes; exit 1 when there are any"], ["--unlink", "remove what the adapter installed"], ["--home HOME", "home directory to install into"]],
  options: { write: { type: "boolean" }, check: { type: "boolean" }, unlink: { type: "boolean" }, home: { type: "string" } },
};

export interface LinkMode {
  write: boolean;
  check: boolean;
  unlink: boolean;
}

function environmentPath(name: string, fallback: string): string {
  return expandUser(cleanPath(process.env[name] ?? fallback));
}

export function hookRuntime(binary: string = process.execPath, searchPath: string = process.env["PATH"] ?? ""): string {
  const actual = resolvePath(binary);
  for (const directory of searchPath.split(":").filter(isAbsolute)) {
    const launcher = childPath(directory, basename(binary));
    if (isFile(launcher) && resolvePath(launcher) === actual) return launcher;
  }
  return binary;
}

function readOptions(argv: readonly string[]): { mode: LinkMode; home: string | undefined } | CommandResult {
  return parseOrExit(() => {
    const parsed = parseCommandLine(LINK_COMMAND, [...argv]);
    refuseEndOfOptions(LINK_COMMAND, argv);
    noPositionals(LINK_COMMAND, parsed);
    const chosen = MODE_FLAGS.filter((flag) => parsed.values[flag] === true);
    const [first, second] = chosen;
    if (first !== undefined && second !== undefined) usageError(LINK_COMMAND, `argument --${second}: not allowed with argument --${first}`);
    const home = parsed.values["home"];
    return {
      mode: { write: chosen.includes("write"), check: chosen.includes("check"), unlink: chosen.includes("unlink") },
      home: typeof home === "string" ? home : undefined,
    };
  });
}

export function main(argv: readonly string[]): CommandResult {
  const options = readOptions(argv);
  if (isCommandResult(options)) return options;
  const { mode } = options;
  const home = resolvePath(expandUser(cleanPath(options.home ?? expandUser("~"))));
  const codexHome = resolvePath(environmentPath("CODEX_HOME", childPath(home, ".codex")));
  const overlay = resolvePath(environmentPath("KEEL_OVERLAY_DIR", childPath(home, "git/keel-overlay")));
  const keelDataDirectory = absolutePath(environmentPath("KEEL_DATA_DIR", childPath(home, ".claude")));
  const agentsHome = childPath(home, ".agents");
  try {
    return withInstallationLock(agentsHome, mode.write || mode.unlink, () => {
      const desired = mode.unlink ? new Map<string, ManagedFile>() : buildFiles(codexHome, overlay, keelDataDirectory, agentsHome);
      const skills = mode.unlink ? new Map<string, ManagedFile>() : buildSkillLinks(home, overlay);
      return reconcile(desired, skills, agentsHome, childPath(codexHome, STATE_NAME), mode);
    });
  } catch (error) {
    const message = refusalMessage(error);
    if (message === null) throw error;
    return { code: REFUSED_EXIT_CODE, stdout: "", stderr: `codex/link: refused: ${message}\n` };
  }
}

export function buildFiles(codexHome: string, overlay: string, data: string, agentsHome: string, keelRoot: string = KEEL_ROOT): Map<string, ManagedFile> {
  const adapter = childPath(keelRoot, "codex");
  const principles = readText(childPath(keelRoot, "PRINCIPLES.md"));
  const personal = childPath(overlay, "PERSONAL.md");
  const owner = isFile(personal) ? readText(personal) : "";
  const runtime = readText(childPath(adapter, "AGENTS.md"));
  const paths: Array<[string, string]> = [["KEEL_HOME", keelRoot], ["KEEL_OVERLAY_DIR", overlay], ["KEEL_DATA_DIR", data]];
  const locations = paths.map(([key, value]) => `- ${key}: \`${value}\``).join("\n");
  const agents = GENERATED_HEADER +
    [principles, owner, runtime, "## Runtime paths", locations, `- keel CLI: \`${childPath(keelRoot, "bin/keel")}\`\n`].join("\n");
  paths.push(["KEEL_CODEX_HOME", codexHome], ["KEEL_AGENTS_HOME", agentsHome]);
  const assignments = paths.map(([key, value]) => `${key}=${shlexQuote(value)}`).join(" ");
  const command = `${assignments} ${shlexQuote(hookRuntime())} ${shlexQuote(childPath(keelRoot, HOOK_SCRIPT))}`;
  const hooks: JsonValue = {
    hooks: {
      PreToolUse: [{
        matcher: "Bash|apply_patch|Edit|Write",
        hooks: [{ type: "command", command, timeout: HOOK_TIMEOUT_SECONDS }],
      }],
    },
  };
  return new Map<string, ManagedFile>([
    [childPath(codexHome, "AGENTS.md"), { kind: "file", content: agents }],
    [childPath(codexHome, "hooks.json"), { kind: "file", content: JSON.stringify(hooks, null, JSON_INDENT) + "\n" }],
  ]);
}

export function buildSkillLinks(home: string, overlay: string, keelRoot: string = KEEL_ROOT): Map<string, ManagedFile> {
  const links = new Map<string, ManagedFile>();
  for (const root of [childPath(keelRoot, "skills"), childPath(overlay, "skills"), childPath(keelRoot, "codex/skills")]) {
    if (!isDirectory(root)) continue;
    for (const name of sortedByCodePoint(readdirSync(root))) {
      const skill = childPath(root, name);
      if (!isFile(childPath(skill, "SKILL.md"))) continue;
      const target = childPath(home, `.agents/skills/${name}`);
      if (links.has(target)) throw new Refusal(`duplicate skill: ${name}`);
      links.set(target, { kind: "link", content: resolvePath(skill) });
    }
  }
  return links;
}

export function reconcile(
  desired: Map<string, ManagedFile>, skills: Map<string, ManagedFile>, agentsHome: string, statePath: string, mode: LinkMode,
  files: SkillFiles = realSkillFiles,
): CommandResult {
  const { owned, migrated } = readProfile(statePath, agentsHome);
  const skillPlan = planSkills(agentsHome, dirname(statePath), skills);
  const { changes, problems } = planFiles(desired, owned);
  problems.push(...skillPlan.problems);
  const actions = [...changes, ...skillPlan.create.keys(), ...Array.from(skillPlan.replace.keys(), (path) => `retarget ${path}`),
    ...skillPlan.remove.map((path) => `remove ${path}`)];
  if (skillPlan.changed) actions.push("update shared skill references");
  if (migrated) actions.push("migrate profile ownership; preserve legacy skill links");
  if (problems.length > 0) {
    const stdout = JSON.stringify({ actions, problems, written: 0 }) + "\n";
    return { code: mode.write || mode.unlink ? REFUSED_EXIT_CODE : mode.check ? CHECK_PENDING_EXIT_CODE : 0, stdout, stderr: "" };
  }
  if (mode.unlink) {
    applySkillPlan(agentsHome, skillPlan, files);
    for (const name of owned.keys()) removeIfPresent(name);
    removeIfPresent(statePath);
    return { code: 0, stdout: JSON.stringify({ removed: owned.size + skillPlan.remove.length }) + "\n", stderr: "" };
  }
  if (mode.write) writeAll(desired, changes, skillPlan, owned, agentsHome, statePath, files);
  const stdout = JSON.stringify({ actions, problems: [] }) + "\n";
  return { code: mode.check && actions.length > 0 ? CHECK_PENDING_EXIT_CODE : 0, stdout, stderr: "" };
}

function removeIfPresent(path: string): void {
  try {
    unlinkSync(path);
  } catch (error) {
    if (!isSystemError(error) || error.code !== "ENOENT") throw error;
  }
}

function writeAll(
  desired: Map<string, ManagedFile>, changes: readonly string[], skillPlan: SkillPlan,
  owned: Map<string, string>, agentsHome: string, statePath: string, files: SkillFiles,
): void {
  for (const path of changes) {
    const file = desired.get(path) as ManagedFile;
    writeAtomic(path, file.content);
    owned.set(path, digest(file.kind, file.content));
  }
  applySkillPlan(agentsHome, skillPlan, files);
  for (const [path, file] of desired) {
    if (owned.has(path)) owned.set(path, digest(file.kind, file.content));
  }
  writeAtomic(statePath, JSON.stringify({ owned: Object.fromEntries(owned), skills_home: agentsHome }, null, JSON_INDENT) + "\n");
}

function readProfile(statePath: string, agentsHome: string): { owned: Map<string, string>; migrated: boolean } {
  const state = readJson(statePath);
  const recorded = Object.hasOwn(state, "owned") ? state["owned"] : {};
  if (!isJsonObject(recorded) || Object.values(recorded).some((value) => typeof value !== "string")) {
    throw new Refusal(`invalid ownership state: ${statePath}`);
  }
  const homeOnRecord = Object.hasOwn(state, "skills_home") ? state["skills_home"] : agentsHome;
  if (homeOnRecord !== agentsHome) throw new Refusal("profile belongs to a different skills home; use its original --home");
  const allowed = new Set(["AGENTS.md", "hooks.json"].map((name) => childPath(dirname(statePath), name)));
  const skillsRoot = childPath(agentsHome, "skills");
  const owned = new Map(Object.entries(recorded as { [key: string]: string }));
  const legacy = new Set(Array.from(owned.keys()).filter((name) => dirname(name) === skillsRoot));
  if (Array.from(owned.keys()).some((name) => !allowed.has(name) && !legacy.has(name))) {
    throw new Refusal("profile ownership contains an unexpected path");
  }
  for (const name of legacy) owned.delete(name);
  return { owned, migrated: Object.keys(state).length > 0 && !Object.hasOwn(state, "skills_home") };
}

function planFiles(desired: Map<string, ManagedFile>, owned: Map<string, string>): { changes: string[]; problems: string[] } {
  const changes: string[] = [];
  const problems: string[] = [];
  const expected = new Map(Array.from(desired, ([path, file]) => [path, digest(file.kind, file.content)] as const));
  for (const [name, recorded] of owned) {
    const current = fingerprint(cleanPath(name));
    if (current !== null && current !== recorded && current !== expected.get(name)) problems.push(`managed path edited: ${name}`);
  }
  for (const [path, file] of desired) {
    const current = fingerprint(path);
    if (current === digest(file.kind, file.content)) continue;
    if (current !== null && current !== owned.get(path)) problems.push(`conflict: ${path}; preserve it and reconcile manually`);
    else changes.push(path);
  }
  return { changes, problems };
}

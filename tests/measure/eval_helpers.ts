import { spawnSync } from "node:child_process"
import fs from "node:fs"
import path from "node:path"

import { CHECKOUT, MeasureSandbox, charterRow } from "./helpers.ts"
import type { Completed } from "./helpers.ts"

export const STUBS_DIR = path.join(CHECKOUT, "tests", "measure", "stubs")
export const EVAL_TOOL = path.join(CHECKOUT, "measure", "evals", "eval.ts")
export const EVAL_ID = "K4"
export const SKILL = "prompt-refine"
export const MODEL = "stub-model"
export const CLI_VERSION = "2.1.296"
const CASE_COLUMNS = ["id", "kind", "expect", "prompt"] as const
export const GENERATED_HEADER = "<!-- GENERATED by keel bin/link from PRINCIPLES.md + PERSONAL.md. Edit the sources, then run bin/link --write. -->"
export const ASK_TEXT = "QUESTION: Which screen do you mean?"
export const ANSWER_TEXT = "The dev server listens on port 4317."

export type CaseRow = Record<(typeof CASE_COLUMNS)[number], string>
export type StreamEvent = Record<string, unknown>
export interface Round {
  events: StreamEvent[]
  exit: number
  writes: Record<string, string>
}
export interface RawRun {
  case: string
  kind: string
  events: StreamEvent[]
  changed?: boolean
  run?: number
  fault?: string
  leftover?: string | null
}

export function caseRow(caseId: string, kind: string, prompt: string, expect: string = "-"): CaseRow {
  return { id: caseId, kind, expect, prompt }
}

export function readJson(file: string): any {
  return JSON.parse(fs.readFileSync(file, "utf8"))
}

export function readJsonl(file: string): any[] {
  if (!fs.existsSync(file)) return []
  return fs.readFileSync(file, "utf8").split("\n").filter((line) => line.trim() !== "").map((line) => JSON.parse(line))
}

export function initEvent(model: string = MODEL): StreamEvent {
  return { type: "system", subtype: "init", model, claude_code_version: CLI_VERSION, tools: ["Skill", "Read", "Edit", "Write"] }
}

export function toolUse(name: string, input: object, parentToolUseId: string | null = null): StreamEvent {
  return { type: "assistant", parent_tool_use_id: parentToolUseId, message: { role: "assistant", content: [{ type: "tool_use", name, input }] } }
}

export function resultEvent(text: string = "Done.", options: { subtype?: string; isError?: boolean; denials?: string[]; modelUsage?: boolean } = {}): StreamEvent {
  const { subtype = "success", isError = false, denials = [], modelUsage = true } = options
  return {
    type: "result", subtype, is_error: isError, result: text,
    modelUsage: modelUsage ? { [MODEL]: { inputTokens: 1 } } : {},
    permission_denials: denials.map((name) => ({ tool_name: name, tool_use_id: "t", tool_input: {} })),
  }
}

export const ASK_EVENT = toolUse("AskUserQuestion", { questions: [] })
export const SKILL_EVENT = toolUse("Skill", { skill: SKILL })
export const EDIT_EVENT = toolUse("Edit", { file_path: "README.md" })

export class EvalSandbox extends MeasureSandbox {
  readonly scenarios: string

  constructor() {
    super()
    this.scenarios = path.join(this.root, "scenarios")
    fs.mkdirSync(this.scenarios)
    this.env["PATH"] = STUBS_DIR + path.delimiter + (this.env["PATH"] ?? "")
    this.env["KEEL_TEST_SCENARIOS"] = this.scenarios
    this.env["CLAUDE_CONFIG_DIR"] = this.data
    this.writeLedger("keel/ledger.tsv", [charterRow(EVAL_ID, { layer: "skill", enforced_at: "skill:" + SKILL, why_not_stronger: "Semantic.", metric: "evals:" + EVAL_ID })])
    this.write("keel/measure/evals/K4/repo/README.md", "# demo\n")
    this.write("keel/measure/evals/K4/repo/notes.txt", "port 4317\n")
  }

  writeCases(relativePath: string, rows: CaseRow[]): string {
    const lines = [CASE_COLUMNS.join("\t"), ...rows.map((row) => CASE_COLUMNS.map((column) => row[column]).join("\t"))]
    return this.write(relativePath, lines.join("\n") + "\n")
  }

  scenario(name: string, options: { events?: StreamEvent[]; exit?: number; writes?: Record<string, string>; sleep?: number; leaveProjectDir?: boolean; rounds?: Round[] } = {}): string {
    const { events = [], exit = 0, writes = {}, sleep = 0, leaveProjectDir = false, rounds } = options
    const body = rounds ? { rounds } : { events, exit, writes, sleep, leave_project_dir: leaveProjectDir }
    this.write(`scenarios/${name}.json`, JSON.stringify(body))
    return name
  }

  round(events: StreamEvent[], writes: Record<string, string> = {}): Round {
    return { events, exit: 0, writes }
  }

  askScenario(name: string = "ask"): string {
    return this.scenario(name, { events: [initEvent(), ASK_EVENT, resultEvent(ASK_TEXT)] })
  }

  editScenario(name: string = "edit"): string {
    return this.scenario(name, { events: [initEvent(), EDIT_EVENT, resultEvent("Renamed it.")], writes: { "README.md": "# demo renamed\n" } })
  }

  seedSuite(ambiguous: string, clear: string): void {
    this.writeCases("keel/measure/evals/K4/train.tsv", [caseRow("a1", "ambiguous", ambiguous), caseRow("c1", "clear-change", clear)])
    this.writeCases("keel/measure/evals/K4/holdout.tsv", [caseRow("h1", "ambiguous", ambiguous), caseRow("h2", "clear-change", clear)])
  }

  linkKeel(): void {
    this.write(`keel/skills/${SKILL}/SKILL.md`, "# skill\n")
    fs.mkdirSync(path.join(this.data, "skills"), { recursive: true })
    fs.symlinkSync(path.join(this.keel, "skills", SKILL), path.join(this.data, "skills", SKILL))
    this.write("data/CLAUDE.md", GENERATED_HEADER + "\n# Principles\n")
  }

  writeRawDir(name: string, runs: RawRun[], options: { summaryEvalId?: string; repeat?: number; keelLive?: boolean; cases?: string[]; evalId?: string } = {}): string {
    const { summaryEvalId = EVAL_ID, repeat = 1, keelLive = true, evalId = EVAL_ID } = options
    const raw = `data/logs/keel-eval-${name}`
    const cases = options.cases ?? [...new Set(runs.map((run) => run.case))]
    this.write(raw + "/config.json", JSON.stringify({
      eval_id: evalId, summary_eval_id: summaryEvalId, keel_live: keelLive, config_dir: this.data,
      model_requested: MODEL, model_observed: MODEL, repeat, cases, command: ["claude", "-p"],
    }))
    const records = runs.map((run) => {
      const stem = `${raw}/${run.case}-${run.run ?? 1}`
      this.write(stem + ".stream.jsonl", run.events.map((event) => JSON.stringify(event) + "\n").join(""))
      this.write(stem + ".diff", "")
      const record: Record<string, unknown> = {
        case: run.case, run: run.run ?? 1, kind: run.kind, exit: 0, timed_out: false, changed: run.changed ?? false, fault: run.fault ?? null, pass: false,
      }
      if (run.leftover !== undefined) record["leftover_project_dir"] = run.leftover
      return record
    })
    this.write(raw + "/runs.jsonl", records.map((record) => JSON.stringify(record) + "\n").join(""))
    return path.join(this.root, raw)
  }

  runEval(...args: string[]): Completed {
    return spawnSync(process.execPath, [EVAL_TOOL, ...args], { encoding: "utf8", env: this.env, cwd: this.root })
  }

  runEvalJson(...args: string[]): [Completed, any] {
    const completed = this.runEval(...args)
    return [completed, completed.stdout.trim() ? JSON.parse(completed.stdout) : null]
  }

  evalLines(): any[] {
    return readJsonl(path.join(this.data, "logs", "keel-evals.jsonl"))
  }

  stubCalls(): any[] {
    return readJsonl(path.join(this.scenarios, "calls.jsonl"))
  }

  rawDirs(): string[] {
    const logs = path.join(this.data, "logs")
    if (!fs.existsSync(logs)) return []
    return fs.readdirSync(logs).filter((name) => name.startsWith("keel-eval-")).sort().map((name) => path.join(logs, name))
  }
}

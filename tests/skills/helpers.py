BULLET = re.compile(r'^\s*(?:[-*+]|\d+\.)\s+')
TAG = re.compile(r'\[([A-Za-z0-9.-]+)\]')


def read(path):
    with open(path, encoding='utf-8') as f:
        return f.read()


def skill_paths():
    return sorted(os.path.join(SKILLS_DIR, name, 'SKILL.md') for name in os.listdir(SKILLS_DIR)
                  if os.path.isfile(os.path.join(SKILLS_DIR, name, 'SKILL.md')))


def rules_section(text):
    """Lines of the `## Rules` section up to the next `## ` heading, skipping fenced code blocks."""
    lines, inside, fenced = [], False, False
    for line in text.splitlines():
        if line.startswith('```'):
            fenced = not fenced
            continue
        if fenced:
            continue
        if line.startswith('## '):
            inside = re.match(RULES_HEADING_PATTERN, line) is not None
            continue
        if inside:
            lines.append(line)
    return lines


def bullet_tags(lines):
    """[(line, first [ID] or None)] for every bullet line: the tag must directly follow the bullet marker."""
    found = []
    for line in lines:
        marker = BULLET.match(line)
        if not marker:
            continue
        tag = re.match(r'\[([A-Za-z0-9.-]+)\]', line[marker.end():])
        found.append((line, tag.group(1) if tag else None))
    return found


class IsolatedTestCase(unittest.TestCase):
    """A fresh temp dir per test; git and keel data never reach the real home or ~/.claude."""

    def setUp(self):
        self.tmp = os.path.realpath(tempfile.mkdtemp(prefix='keel-skills-'))
        self.addCleanup(shutil.rmtree, self.tmp, True)
        gitconfig = os.path.join(self.tmp, 'gitconfig')
        with open(gitconfig, 'w', encoding='utf-8') as f:
            f.write('[user]\n\tname = keel-test\n\temail = keel-test@localhost\n'
                    '[init]\n\tdefaultBranch = main\n[protocol "file"]\n\tallow = always\n')
        os.makedirs(os.path.join(self.tmp, 'home'))
        self.env = dict(os.environ, KEEL_DATA_DIR=os.path.join(self.tmp, 'data'),
                        KEEL_OVERLAY_DIR=os.path.join(self.tmp, 'overlay'), HOME=os.path.join(self.tmp, 'home'),
                        GIT_CONFIG_GLOBAL=gitconfig, GIT_CONFIG_NOSYSTEM='1', KEEL_HOME=KEEL_HOME,
                        KEEL_GH=os.path.join(self.tmp, 'no-gh'))
        for name in ('GIT_DIR', 'GIT_WORK_TREE', 'GIT_INDEX_FILE'):
            self.env.pop(name, None)
        assert self.env['KEEL_DATA_DIR'].startswith(self.tmp + os.sep), 'KEEL_DATA_DIR must be under the test temp dir'

    def git(self, repo, *args, extra_env=None):
        completed = subprocess.run(['git', '-C', repo, *args], capture_output=True, text=True,
                                   env=dict(self.env, **(extra_env or {})))
        if completed.returncode != 0:
            raise AssertionError(f'git {args} failed: {completed.stderr}')
        return completed.stdout.strip()

    def new_repo(self, name):
        repo = os.path.join(self.tmp, name)
        os.makedirs(repo)
        self.git(repo, 'init', '-q', '-b', 'main')
        return repo

    def write(self, repo, path, content):
        full = os.path.join(repo, path)
        os.makedirs(os.path.dirname(full), exist_ok=True)
        with open(full, 'w', encoding='utf-8') as f:
            f.write(content)

    def commit_all(self, repo):
        self.git(repo, 'add', '-A')
        self.git(repo, 'commit', '-q', '--allow-empty', '-m', 'fixture')
        return self.git(repo, 'rev-parse', 'HEAD')

    def add_submodule(self, parent, source, name):
        self.git(parent, 'submodule', 'add', '-q', source, name)

    def snapshot_tree(self, repo):
        """The `keel snapshot` contract: a temp-index tree of the working tree, real index untouched."""
        index = {'GIT_INDEX_FILE': os.path.join(self.tmp, 'snapshot-index')}
        self.git(repo, 'read-tree', 'HEAD', extra_env=index)
        self.git(repo, 'add', '-A', extra_env=index)
        return self.git(repo, 'write-tree', extra_env=index)

    def run_rule_checks(self, *args):
        completed = subprocess.run([sys.executable, RULE_CHECKS, *args], capture_output=True, text=True, env=self.env)
        lines = completed.stdout.strip().splitlines()
        signals = {tuple(line.split(' ', 3)[1:3]) for line in lines if line.startswith('signal ')}
        summary = lines[-1] if lines else ''
        return completed.returncode, signals, summary, lines

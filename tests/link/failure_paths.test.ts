type Outcome = Omit<LinkResult, "json"> & { tree: unknown }

const RECORDED_OUTCOMES = readFixtureOutcomes("failure-paths.json", SCRATCH_ROOT)

function treeOf(root: string): unknown {
  return fs.statSync(root).isDirectory() ? snapshotTree(root) : fs.readFileSync(root, "latin1")
}

function outcomeOf(command: string[], setup: (box: LinkSandbox) => void, args: string[]): Outcome {
  const box = new LinkSandbox({ root: SCRATCH_ROOT })
  try {
    setup(box)
    const completed = box.runLinkRaw(command, ...args)
    return maskDigests({ ...completed, stdout: normalizeStamps(completed.stdout), stderr: normalizeStamps(completed.stderr), tree: treeOf(box.data) })
  } finally {
    fs.chmodSync(box.data, 0o700)
    box.remove()
  }
}

describe("link failure paths keep their exit code, JSON output, stderr kinds and data dir", () => {
  for (const [name, setup, args, status] of FAILURE_CASES) {
    it(`${name}_exitsWith${status}AndKeepsItsOutcome`, { skip: RUNNING_AS_ROOT && name === "dataDirIsReadOnly" }, () => {
      const outcome = outcomeOf([process.execPath, LINK_ENTRY], setup, args)
      const summary = { stdout: summarizeStdout(outcome.stdout), stderr: summarizeStderr(outcome.stderr), tree: summarizeTree(outcome.tree) }
      assert.equal(outcome.status, status, outcome.stderr)
      assert.deepEqual(summary, RECORDED_OUTCOMES[name])
    })
  }

  it("recordedOutcomes_belongOnlyToCasesThatStillExist", () => {
    assert.deepEqual(Object.keys(RECORDED_OUTCOMES).sort(), FAILURE_CASES.map(([name]) => name).sort())
  })
})

type DivergentOutcome = Omit<LinkResult, "json"> & { before: unknown; after: unknown; linkStatePath: string }

function runUnlinkOnce(entry: string[], divergence: IntendedDivergence): DivergentOutcome {
  const box = new LinkSandbox({ root: SCRATCH_ROOT })
  try {
    withLinkState(`{"pre_keel_settings_backup": ${divergence.literal}}`)(box)
    const before = treeOf(box.data)
    const completed = box.runLinkRedirected(entry, divergence.redirected, "--unlink")
    return { ...completed, before, after: treeOf(box.data), linkStatePath: box.dataPath(LINK_STATE) }
  } finally {
    box.remove()
  }
}


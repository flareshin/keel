import os
import unittest

from helpers import KEEL_ROOT, PRINCIPLES, LinkTestCase, read_file
from link.claude_md import HEADER


class LinkClaudeMdTest(LinkTestCase):
    def test_write_requiresExplicitPrRequest_inGeneratedSourceGuidance(self):
        self.box.write_keel("PRINCIPLES.md", read_file(os.path.join(KEEL_ROOT, "PRINCIPLES.md")))

        result = self.box.run_link("--write")

        self.assertExit(result, 0)
        self.assertIn("Create PRs only on explicit user request; PASS is not consent.",
                      self.box.read_data("CLAUDE.md"))

    def test_write_generatesHeaderPrinciplesAndPersonal_whenOverlayHasPersonal(self):
        # when
        result = self.box.run_link("--write")
        # then
        self.assertExit(result, 0)
        with open(os.path.join(self.box.overlay, "PERSONAL.md"), encoding="utf-8") as f:
            personal = f.read()
        self.assertEqual(self.box.read_data("CLAUDE.md"), HEADER + "\n" + PRINCIPLES + "\n" + personal)

    def test_write_generatesHeaderAndPrinciplesOnly_whenOverlayHasNoPersonal(self):
        # given
        os.unlink(os.path.join(self.box.overlay, "PERSONAL.md"))
        # when
        result = self.box.run_link("--write")
        # then
        self.assertExit(result, 0)
        self.assertEqual(self.box.read_data("CLAUDE.md"), HEADER + "\n" + PRINCIPLES)

    def test_write_addsFinalNewline_whenPrinciplesLacksOne(self):
        # given
        self.box.write_keel("PRINCIPLES.md", "- [K1] No newline")
        os.unlink(os.path.join(self.box.overlay, "PERSONAL.md"))
        # when
        self.assertExit(self.box.run_link("--write"), 0)
        # then
        self.assertEqual(self.box.read_data("CLAUDE.md"), HEADER + "\n- [K1] No newline\n")

    def test_dryRun_reportsTheGeneratedClaudeMdSize_beforeAnyWrite(self):
        # given non-ASCII text, so bytes and characters differ
        os.unlink(os.path.join(self.box.overlay, "PERSONAL.md"))
        self.box.write_keel("PRINCIPLES.md", "- [K1] caf\u00e9\n")
        # when
        result = self.box.run_link()
        # then
        self.assertExit(result, 0)
        self.assertEqual(result.json["claude_md_bytes"], len((HEADER + "\n- [K1] caf\u00e9\n").encode("utf-8")))

    def test_dryRun_reportsTheGeneratedClaudeMdSize_whenTheLiveFileIsCurrent(self):
        # given
        self.assertExit(self.box.run_link("--write"), 0)
        # when
        result = self.box.run_link()
        # then
        self.assertEqual(result.json["claude_md_bytes"], os.path.getsize(self.box.data_path("CLAUDE.md")))

    def test_write_refusesAndWritesNothing_whenGeneratedFileExceeds4096Bytes(self):
        # given
        self.box.write_overlay("PERSONAL.md", "x" * 4096)
        # when
        result = self.box.run_link("--write")
        # then
        self.assertExit(result, 3)
        self.assertEqual(self.problem_kinds(result), ["claude-md-drift"])
        self.assertIn("4096-byte cap", result.json["problems"][0]["detail"])
        self.assertFalse(os.path.exists(self.box.data_path("CLAUDE.md")))
        self.assertFalse(os.path.lexists(self.box.data_path("bin/keel")))

    def test_write_succeeds_whenGeneratedFileIsExactly4096Bytes(self):
        # given
        os.unlink(os.path.join(self.box.overlay, "PERSONAL.md"))
        filler = 4096 - len((HEADER + "\n").encode()) - 1
        self.box.write_keel("PRINCIPLES.md", "y" * filler + "\n")
        # when
        result = self.box.run_link("--write")
        # then
        self.assertExit(result, 0)
        self.assertEqual(len(self.box.read_data("CLAUDE.md").encode()), 4096)

    def test_write_refuses_whenExistingClaudeMdIsHandWrittenWithoutForce(self):
        # given a v1 CLAUDE.md without the generated header
        self.box.write_data("CLAUDE.md", "# my v1 rules\n")
        # when
        result = self.box.run_link("--write")
        # then
        self.assertExit(result, 3)
        self.assertEqual(self.problem_kinds(result), ["target-occupied"])
        self.assertEqual(self.box.read_data("CLAUDE.md"), "# my v1 rules\n")

    def test_write_movesHandWrittenClaudeMdAsideAndGenerates_whenForced(self):
        # given
        self.box.write_data("CLAUDE.md", "# my v1 rules\n")
        # when
        result = self.box.run_link("--write", "--force")
        # then
        self.assertExit(result, 0)
        self.assertIn({"op": "write-claude-md", "path": self.box.data_path("CLAUDE.md")}, result.json["actions"])
        self.assertTrue(self.box.read_data("CLAUDE.md").startswith("<!-- GENERATED by keel bin/link"))
        self.assertEqual(read_file(self.only_backup("CLAUDE.md")), "# my v1 rules\n")

    def test_write_regenerates_whenGeneratedFileWasEdited(self):
        # given
        self.assertExit(self.box.run_link("--write"), 0)
        expected = self.box.read_data("CLAUDE.md")
        self.box.write_data("CLAUDE.md", expected + "- local edit\n")
        # when
        result = self.box.run_link("--write")
        # then
        self.assertExit(result, 0)
        self.assertEqual(result.json["actions"], [{"op": "write-claude-md", "path": self.box.data_path("CLAUDE.md")}])
        self.assertEqual(self.box.read_data("CLAUDE.md"), expected)

    def test_write_refuses_whenPrinciplesIsMissing(self):
        # given
        os.unlink(os.path.join(self.box.keel, "PRINCIPLES.md"))
        # when
        result = self.box.run_link("--write")
        # then
        self.assertExit(result, 3)
        self.assertIn("PRINCIPLES.md is missing", result.stderr)


if __name__ == "__main__":
    unittest.main()

import { spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readdirSync, readFileSync, realpathSync, rmSync, statSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, sep } from "node:path";
import { splitlines } from "../../hooks/lib/hookkit/text.ts";

export const KEEL_HOME = realpathSync(join(import.meta.dirname, "..", ".."));
export const SKILLS_DIR = join(KEEL_HOME, "skills");
export const AGENTS_DIR = join(KEEL_HOME, "agents");
export const PRINCIPLES = join(KEEL_HOME, "PRINCIPLES.md");
export const RULE_CHECKS = join(SKILLS_DIR, "readable-code", "scripts", "rule-checks.ts");
export const GENERATED_HEADER = "<!-- GENERATED by keel bin/link from PRINCIPLES.md + PERSONAL.md. Edit the sources, then run bin/link --write. -->";

const RULES_HEADING = /^##[ \t\r\n\f\v]+Rules(?![\p{L}\p{N}_])/iu;
const SEED_IDS = new Set(["K1", "K2", "K3", "K4", "K5", "risk", "F-irreversible", "F-secrets", "F-attribution",
  "F-force-push", "F-hookskip", "C-dispatch", "C-handoff", "C-isolation", "S-jdk"]);
export const K5_SUB_IDS = new Set(Array.from({ length: 16 }, (_unused, index) => `K5.${index + 1}`));
export const VALID_IDS = new Set([...SEED_IDS, ...K5_SUB_IDS]);

const BULLET = /^[ \t\r\n\f\v]*(?:[-*+]|\p{Nd}+\.)[ \t\r\n\f\v]+/u;

export function read(path: string): string {
  return readFileSync(path, "utf8");
}

export function skillPaths(): string[] {
  return readdirSync(SKILLS_DIR).sort()
    .map((name) => join(SKILLS_DIR, name, "SKILL.md"))
    .filter((path) => {
      try {
        return statSync(path).isFile();
      } catch {
        return false;
      }
    });
}

export function agentPaths(): string[] {
  return readdirSync(AGENTS_DIR).sort().filter((name) => name.endsWith(".md")).map((name) => join(AGENTS_DIR, name));
}

export function markdownPaths(): string[] {
  const skillMarkdown = readdirSync(SKILLS_DIR, { recursive: true, encoding: "utf8" }).sort()
    .filter((name) => name.endsWith(".md"))
    .map((name) => join(SKILLS_DIR, name));
  return [...skillMarkdown, ...agentPaths()];
}

export function rulesSection(text: string): string[] {
  const lines: string[] = [];
  let inside = false;
  let fenced = false;
  for (const line of splitlines(text)) {
    if (line.startsWith("```")) {
      fenced = !fenced;
      continue;
    }
    if (fenced) continue;
    if (line.startsWith("## ")) {
      inside = RULES_HEADING.test(line);
      continue;
    }
    if (inside) lines.push(line);
  }
  return lines;
}

export function bulletTags(lines: readonly string[]): Array<[string, string | null]> {
  const found: Array<[string, string | null]> = [];
  for (const line of lines) {
    const marker = BULLET.exec(line);
    if (marker === null) continue;
    const tag = /^\[([A-Za-z0-9.-]+)\]/.exec(line.slice(marker[0].length));
    found.push([line, tag === null ? null : (tag[1] as string)]);
  }
  return found;
}

export interface RuleChecksRun {
  code: number | null;
  signals: Set<string>;
  summary: string;
  lines: string[];
}

export class Isolated {
  readonly tmp: string;
  readonly env: NodeJS.ProcessEnv;

  constructor() {
    this.tmp = realpathSync(mkdtempSync(join(realpathSync(tmpdir()), "keel-skills-")));
    const gitconfig = join(this.tmp, "gitconfig");
    writeFileSync(gitconfig, "[user]\n\tname = keel-test\n\temail = keel-test@localhost\n[init]\n\tdefaultBranch = main\n[protocol \"file\"]\n\tallow = always\n");
    mkdirSync(join(this.tmp, "home"));
    this.env = {
      ...process.env, KEEL_DATA_DIR: join(this.tmp, "data"), KEEL_OVERLAY_DIR: join(this.tmp, "overlay"), HOME: join(this.tmp, "home"),
      GIT_CONFIG_GLOBAL: gitconfig, GIT_CONFIG_NOSYSTEM: "1", KEEL_HOME, KEEL_GH: join(this.tmp, "no-gh"),
    };
    for (const name of ["GIT_DIR", "GIT_WORK_TREE", "GIT_INDEX_FILE"]) delete this.env[name];
    if (!(this.env["KEEL_DATA_DIR"] as string).startsWith(this.tmp + sep)) throw new Error("KEEL_DATA_DIR must be under the test temp dir");
  }

  close(): void {
    rmSync(this.tmp, { recursive: true, force: true });
  }

  git(repo: string, args: string[], extraEnv: Record<string, string> = {}): string {
    const completed = spawnSync("git", ["-C", repo, ...args], { encoding: "utf8", env: { ...this.env, ...extraEnv } });
    if (completed.status !== 0) throw new Error(`git ${JSON.stringify(args)} failed: ${completed.stderr}`);
    return completed.stdout.trim();
  }

  newRepo(name: string): string {
    const repo = join(this.tmp, name);
    mkdirSync(repo);
    this.git(repo, ["init", "-q", "-b", "main"]);
    return repo;
  }

  write(repo: string, path: string, content: string | Buffer): void {
    const full = join(repo, path);
    mkdirSync(dirname(full), { recursive: true });
    writeFileSync(full, content);
  }

  commitAll(repo: string): string {
    this.git(repo, ["add", "-A"]);
    this.git(repo, ["commit", "-q", "--allow-empty", "-m", "fixture"]);
    return this.git(repo, ["rev-parse", "HEAD"]);
  }

  addSubmodule(parent: string, source: string, name: string): void {
    this.git(parent, ["submodule", "add", "-q", source, name]);
  }

  snapshotTree(repo: string): string {
    const index = { GIT_INDEX_FILE: join(this.tmp, "snapshot-index") };
    this.git(repo, ["read-tree", "HEAD"], index);
    this.git(repo, ["add", "-A"], index);
    return this.git(repo, ["write-tree"], index);
  }

  runRuleChecks(...args: string[]): RuleChecksRun {
    const completed = spawnSync(process.execPath, [RULE_CHECKS, ...args], { encoding: "utf8", env: this.env });
    const lines = splitlines(completed.stdout.trim());
    const signals = new Set(lines.filter((line) => line.startsWith("signal ")).map((line) => line.split(" ").slice(1, 3).join(" ")));
    return { code: completed.status, signals, summary: lines[lines.length - 1] ?? "", lines };
  }
}

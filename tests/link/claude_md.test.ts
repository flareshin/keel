import assert from "node:assert/strict"
import { afterEach, beforeEach, describe, it } from "node:test"
import fs from "node:fs"
import path from "node:path"

import { HEADER } from "../../lib/link/claude_md.ts"
import { KEEL_ROOT, LinkSandbox, PRINCIPLES, assertExit, lexistsPath, onlyBackup, problemKinds, readFile } from "./helpers.ts"

describe("link claude md", () => {
  let box: LinkSandbox

  beforeEach(() => {
    box = new LinkSandbox()
  })
  afterEach(() => box.remove())

  const removePersonal = () => fs.unlinkSync(path.join(box.overlay, "PERSONAL.md"))

  it("write_requiresOwnerApprovalAndShip1_inGeneratedSourceGuidance", () => {
    box.writeKeel("PRINCIPLES.md", readFile(path.join(KEEL_ROOT, "PRINCIPLES.md")))
    const result = box.runLink("--write")
    assertExit(result, 0)
    assert.ok(box.readData("CLAUDE.md").includes("PRs require owner `keel approve` then explicit `/ship1`; PASS is not consent."))
  })

  it("write_generatesHeaderPrinciplesAndPersonal_whenOverlayHasPersonal", () => {
    const result = box.runLink("--write")
    assertExit(result, 0)
    const personal = readFile(path.join(box.overlay, "PERSONAL.md"))
    assert.equal(box.readData("CLAUDE.md"), HEADER + "\n" + PRINCIPLES + "\n" + personal)
  })

  it("write_generatesHeaderAndPrinciplesOnly_whenOverlayHasNoPersonal", () => {
    removePersonal()
    assertExit(box.runLink("--write"), 0)
    assert.equal(box.readData("CLAUDE.md"), HEADER + "\n" + PRINCIPLES)
  })

  it("write_addsFinalNewline_whenPrinciplesLacksOne", () => {
    box.writeKeel("PRINCIPLES.md", "- [K1] No newline")
    removePersonal()
    assertExit(box.runLink("--write"), 0)
    assert.equal(box.readData("CLAUDE.md"), HEADER + "\n- [K1] No newline\n")
  })

  it("dryRun_reportsTheGeneratedClaudeMdSize_beforeAnyWrite", () => {
    removePersonal()
    box.writeKeel("PRINCIPLES.md", "- [K1] caf\u00e9\n")
    const result = box.runLink()
    assertExit(result, 0)
    assert.equal(result.json.claude_md_bytes, Buffer.byteLength(HEADER + "\n- [K1] caf\u00e9\n", "utf8"))
  })

  it("dryRun_reportsTheGeneratedClaudeMdSize_whenTheLiveFileIsCurrent", () => {
    assertExit(box.runLink("--write"), 0)
    const result = box.runLink()
    assert.equal(result.json.claude_md_bytes, fs.statSync(box.dataPath("CLAUDE.md")).size)
  })

  it("write_refusesAndWritesNothing_whenGeneratedFileExceeds4096Bytes", () => {
    box.writeOverlay("PERSONAL.md", "x".repeat(4096))
    const result = box.runLink("--write")
    assertExit(result, 3)
    assert.deepEqual(problemKinds(result), ["claude-md-drift"])
    assert.ok(result.json.problems[0].detail.includes("4096-byte cap"))
    assert.equal(fs.existsSync(box.dataPath("CLAUDE.md")), false)
    assert.equal(lexistsPath(box.dataPath("bin/keel")), false)
  })

  it("write_succeeds_whenGeneratedFileIsExactly4096Bytes", () => {
    removePersonal()
    const filler = 4096 - Buffer.byteLength(HEADER + "\n") - 1
    box.writeKeel("PRINCIPLES.md", "y".repeat(filler) + "\n")
    const result = box.runLink("--write")
    assertExit(result, 0)
    assert.equal(Buffer.byteLength(box.readData("CLAUDE.md")), 4096)
  })

  it("write_refuses_whenExistingClaudeMdIsHandWrittenWithoutForce", () => {
    box.writeData("CLAUDE.md", "# my v1 rules\n")
    const result = box.runLink("--write")
    assertExit(result, 3)
    assert.deepEqual(problemKinds(result), ["target-occupied"])
    assert.equal(box.readData("CLAUDE.md"), "# my v1 rules\n")
  })

  it("write_movesHandWrittenClaudeMdAsideAndGenerates_whenForced", () => {
    box.writeData("CLAUDE.md", "# my v1 rules\n")
    const result = box.runLink("--write", "--force")
    assertExit(result, 0)
    assert.ok(result.json.actions.some((action: { op: string; path: string }) => action.op === "write-claude-md" && action.path === box.dataPath("CLAUDE.md")))
    assert.ok(box.readData("CLAUDE.md").startsWith("<!-- GENERATED by keel bin/link"))
    assert.equal(readFile(onlyBackup(box, "CLAUDE.md")), "# my v1 rules\n")
  })

  it("write_regenerates_whenGeneratedFileWasEdited", () => {
    assertExit(box.runLink("--write"), 0)
    const expected = box.readData("CLAUDE.md")
    box.writeData("CLAUDE.md", expected + "- local edit\n")
    const result = box.runLink("--write")
    assertExit(result, 0)
    assert.deepEqual(result.json.actions, [{ op: "write-claude-md", path: box.dataPath("CLAUDE.md") }])
    assert.equal(box.readData("CLAUDE.md"), expected)
  })

  it("write_refuses_whenPrinciplesIsMissing", () => {
    fs.unlinkSync(path.join(box.keel, "PRINCIPLES.md"))
    const result = box.runLink("--write")
    assertExit(result, 3)
    assert.ok(result.stderr.includes("PRINCIPLES.md is missing"))
  })
})

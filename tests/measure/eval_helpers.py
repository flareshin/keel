"""Sandbox additions for the eval runner tests: case files, a fixture, a stub `claude` on PATH and canned stream-json."""
from __future__ import annotations

import json
import os
import subprocess
from typing import Dict, List, Optional

from helpers import CHECKOUT, MeasureSandbox, charter_row

STUBS_DIR = os.path.join(CHECKOUT, "tests", "measure", "stubs")
EVAL_TOOL = os.path.join(CHECKOUT, "measure", "evals", "eval")
EVAL_ID = "K4"
SKILL = "prompt-refine"
MODEL = "stub-model"
CLI_VERSION = "2.1.296"
CASE_COLUMNS = ("id", "kind", "expect", "prompt")
GENERATED_HEADER = "<!-- GENERATED by keel bin/link from PRINCIPLES.md + PERSONAL.md. Edit the sources, then run bin/link --write. -->"
ASK_TEXT = "QUESTION: Which screen do you mean?"
ANSWER_TEXT = "The dev server listens on port 4317."


def case_row(case_id: str, kind: str, prompt: str, expect: str = "-") -> Dict[str, str]:
    return {"id": case_id, "kind": kind, "expect": expect, "prompt": prompt}


def read_json(path: str) -> dict:
    with open(path, encoding="utf-8") as handle:
        return json.load(handle)


def read_jsonl(path: str) -> List[dict]:
    """Records of a JSONL file; a missing file is an empty log."""
    if not os.path.exists(path):
        return []
    with open(path, encoding="utf-8") as handle:
        return [json.loads(line) for line in handle if line.strip()]


def init_event(model: str = MODEL) -> dict:
    return {"type": "system", "subtype": "init", "model": model, "claude_code_version": CLI_VERSION, "tools": ["Skill", "Read", "Edit", "Write"]}


def tool_use(name: str, tool_input: dict, parent_tool_use_id: Optional[str] = None) -> dict:
    return {"type": "assistant", "parent_tool_use_id": parent_tool_use_id, "message": {"role": "assistant", "content": [{"type": "tool_use", "name": name, "input": tool_input}]}}


def result_event(text: str = "Done.", subtype: str = "success", is_error: bool = False, denials: tuple = (), model_usage: bool = True) -> dict:
    return {
        "type": "result", "subtype": subtype, "is_error": is_error, "result": text,
        "modelUsage": {MODEL: {"inputTokens": 1}} if model_usage else {},
        "permission_denials": [{"tool_name": name, "tool_use_id": "t", "tool_input": {}} for name in denials],
    }


ASK_EVENT = tool_use("AskUserQuestion", {"questions": []})
SKILL_EVENT = tool_use("Skill", {"skill": SKILL})
EDIT_EVENT = tool_use("Edit", {"file_path": "README.md"})


class EvalSandbox(MeasureSandbox):
    """A keel checkout with a K4 ledger row and a tiny fixture; `claude` on PATH is the stub; the CLI config dir is the data dir."""

    def __init__(self) -> None:
        super().__init__()
        self.scenarios = os.path.join(self.root, "scenarios")
        os.makedirs(self.scenarios)
        self.env["PATH"] = STUBS_DIR + os.pathsep + self.env.get("PATH", "")
        self.env["KEEL_TEST_SCENARIOS"] = self.scenarios
        self.env["CLAUDE_CONFIG_DIR"] = self.data
        self.write_ledger("keel/ledger.tsv", [charter_row(EVAL_ID, layer="skill", enforced_at="skill:" + SKILL, why_not_stronger="Semantic.", metric="evals:" + EVAL_ID)])
        self.write("keel/measure/evals/K4/repo/README.md", "# demo\n")
        self.write("keel/measure/evals/K4/repo/notes.txt", "port 4317\n")

    def write_cases(self, relative_path: str, rows: List[Dict[str, str]]) -> str:
        lines = ["\t".join(CASE_COLUMNS)] + ["\t".join(row[column] for column in CASE_COLUMNS) for row in rows]
        return self.write(relative_path, "\n".join(lines) + "\n")

    def scenario(self, name: str, events: Optional[list] = None, exit_code: int = 0, writes: Optional[dict] = None,
                 sleep: float = 0, leave_project_dir: bool = False, rounds: Optional[list] = None) -> str:
        """Writes the stub's scenario file and returns its name, which doubles as the case prompt."""
        body = {"rounds": rounds} if rounds else {"events": events or [], "exit": exit_code, "writes": writes or {}, "sleep": sleep, "leave_project_dir": leave_project_dir}
        self.write("scenarios/%s.json" % name, json.dumps(body))
        return name

    def round(self, events: list, writes: Optional[dict] = None) -> dict:
        return {"events": events, "exit": 0, "writes": writes or {}}

    def ask_scenario(self, name: str = "ask") -> str:
        return self.scenario(name, [init_event(), ASK_EVENT, result_event(ASK_TEXT)])

    def edit_scenario(self, name: str = "edit") -> str:
        return self.scenario(name, [init_event(), EDIT_EVENT, result_event("Renamed it.")], writes={"README.md": "# demo renamed\n"})

    def seed_suite(self, ambiguous: str, clear: str) -> None:
        """One ambiguous and one clear-change case per split, each playing the given scenario."""
        self.write_cases("keel/measure/evals/K4/train.tsv", [case_row("a1", "ambiguous", ambiguous), case_row("c1", "clear-change", clear)])
        self.write_cases("keel/measure/evals/K4/holdout.tsv", [case_row("h1", "ambiguous", ambiguous), case_row("h2", "clear-change", clear)])

    def link_keel(self) -> None:
        """What bin/link --write leaves behind: the skill symlinked into keel and a generated CLAUDE.md."""
        skill_source = os.path.join(self.keel, "skills", SKILL)
        self.write("keel/skills/%s/SKILL.md" % SKILL, "# skill\n")
        os.makedirs(os.path.join(self.data, "skills"))
        os.symlink(skill_source, os.path.join(self.data, "skills", SKILL))
        self.write("data/CLAUDE.md", GENERATED_HEADER + "\n# Principles\n")

    def run_eval(self, *args: str) -> subprocess.CompletedProcess:
        return subprocess.run([EVAL_TOOL] + list(args), capture_output=True, text=True, env=self.env, cwd=self.root)

    def run_eval_json(self, *args: str):
        completed = self.run_eval(*args)
        return completed, json.loads(completed.stdout) if completed.stdout.strip() else None

    def eval_lines(self) -> List[dict]:
        return read_jsonl(os.path.join(self.data, "logs", "keel-evals.jsonl"))

    def stub_calls(self) -> List[dict]:
        return read_jsonl(os.path.join(self.scenarios, "calls.jsonl"))

    def raw_dirs(self) -> List[str]:
        logs = os.path.join(self.data, "logs")
        return sorted(os.path.join(logs, name) for name in os.listdir(logs) if name.startswith("keel-eval-")) if os.path.isdir(logs) else []
